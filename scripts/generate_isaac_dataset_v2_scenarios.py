#!/usr/bin/env python3
"""Generate six phase-isolated Isaac dataset-v2 capture scenarios."""

from __future__ import annotations

import argparse
from copy import deepcopy
import json
from pathlib import Path

import yaml


PHASES = ("development", "gate", "confirmation")
MODES = ("static", "dynamic")
FOCUSED_CASES = {
    "crossing": "crossing",
    "oncoming": "oncoming",
    "slow": "same_direction_slow",
    "temporary_block": "temporary_block",
}


def build_scenario(
    base: dict[str, object],
    records: list[dict[str, object]],
    *,
    phase: str,
    mode: str,
    scenario_family: str = "",
) -> dict[str, object]:
    payload = deepcopy(base)
    scenario = payload["scenario"]
    family = f"_{scenario_family}" if scenario_family else ""
    scenario["id"] = f"isaac_kujiale_dataset_v2{family}_{phase}_{mode}"
    matrix = []
    for index, record in enumerate(records):
        if mode == "dynamic":
            if record["dynamic_contract"] == "full_route_three_actor":
                case_id = "full_route_three_stage"
            else:
                case_id = FOCUSED_CASES[str(record["dynamic_case"])]
            variant_id = f"v{index % 5 + 1}"
        else:
            case_id = "static"
            variant_id = "dataset_v2_v1"
        matrix.append(
            {
                "seed": int(record["seed"]),
                "case_id": case_id,
                "variant_id": variant_id,
                "condition_id": (
                    f"{mode}_{record['condition']}"
                ),
                "appearance_profile_id": str(
                    record["appearance_profile"]
                ),
            }
        )
    scenario["runs"]["matrix"] = matrix
    return payload


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument(
        "--output-directory",
        type=Path,
        default=Path("ros2_ws/src/robot_experiments/config"),
    )
    parser.add_argument(
        "--scenario-family",
        default="",
        help="Optional filename/id component for an independent seed family.",
    )
    args = parser.parse_args()
    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    records = manifest.get("records", [])
    output = args.output_directory.resolve()
    output.mkdir(parents=True, exist_ok=True)
    config = Path(__file__).resolve().parents[1] / (
        "ros2_ws/src/robot_experiments/config"
    )
    bases = {
        mode: yaml.safe_load(
            (config / f"isaac_kujiale_dataset_v2_smoke_{mode}.yaml").read_text(
                encoding="utf-8"
            )
        )
        for mode in MODES
    }
    generated = []
    for phase in PHASES:
        for mode in MODES:
            selected = [
                row
                for row in records
                if row.get("phase") == phase
                and row.get("environment") == mode
            ]
            expected = 40 if phase == "development" else 10
            if len(selected) != expected:
                raise ValueError(
                    f"{phase}/{mode} expected {expected} records, "
                    f"got {len(selected)}"
                )
            family = (
                f"_{args.scenario_family}" if args.scenario_family else ""
            )
            target = output / (
                f"isaac_kujiale_dataset_v2{family}_{phase}_{mode}.yaml"
            )
            target.write_text(
                "# Generated by scripts/generate_isaac_dataset_v2_scenarios.py.\n"
                f"# Frozen record set: {manifest['record_set_sha256']}.\n"
                + yaml.safe_dump(
                    build_scenario(
                        bases[mode],
                        selected,
                        phase=phase,
                        mode=mode,
                        scenario_family=args.scenario_family,
                    ),
                    sort_keys=False,
                ),
                encoding="utf-8",
            )
            generated.append(str(target))
    print("\n".join(generated))


if __name__ == "__main__":
    main()
