#!/usr/bin/env python3
"""Generate paired-rendering Dataset-v3 scenarios for Attempt-21."""

from __future__ import annotations

import argparse
from copy import deepcopy
import hashlib
import json
from pathlib import Path
from typing import Any

import yaml


PHASES = ("development", "gate", "confirmation")
MODES = ("static", "dynamic")
APPEARANCES = ("dim_warm", "dim_cool", "bright_warm", "bright_cool")
DYNAMIC_CASES = (
    "full_route_three_stage",
    "crossing",
    "oncoming",
    "same_direction_slow",
    "temporary_block",
)


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _seed_range(prereg: dict[str, Any], phase: str, mode: str) -> range:
    first, last = prereg[phase][mode]
    seeds = range(int(first), int(last) + 1)
    expected = 40 if phase == "development" else 10
    if len(seeds) != expected:
        raise ValueError(f"{phase}/{mode} seed family must contain {expected} seeds")
    return seeds


def build_matrix(prereg: dict[str, Any], *, phase: str, mode: str) -> list[dict[str, Any]]:
    """Create baseline/appearance adjacent pairs with identical dynamics."""

    matrix: list[dict[str, Any]] = []
    for offset, seed in enumerate(_seed_range(prereg, phase, mode)):
        appearance = APPEARANCES[offset % len(APPEARANCES)]
        case_id = "static" if mode == "static" else DYNAMIC_CASES[offset % len(DYNAMIC_CASES)]
        variant_id = "dataset_v3_v1" if mode == "static" else f"v{offset % 5 + 1}"
        pair_id = f"{phase}-{mode}-{seed}"
        for profile in ("baseline", appearance):
            matrix.append(
                {
                    "seed": int(seed),
                    "case_id": case_id,
                    "variant_id": variant_id,
                    "condition_id": f"{mode}_{'baseline' if profile == 'baseline' else 'appearance'}",
                    "appearance_profile_id": profile,
                    "pair_id": pair_id,
                }
            )
    return matrix


def build_scenario(
    base: dict[str, Any], prereg: dict[str, Any], *, phase: str, mode: str
) -> dict[str, Any]:
    payload = deepcopy(base)
    scenario = payload["scenario"]
    scenario["id"] = f"isaac_kujiale_dataset_v3_attempt21_{phase}_{mode}"
    # pair_id is an exporter/campaign identity, not part of the runner schema.
    matrix = build_matrix(prereg, phase=phase, mode=mode)
    scenario["runs"]["matrix"] = [
        {key: value for key, value in row.items() if key != "pair_id"}
        for row in matrix
    ]
    return payload


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prereg", type=Path, required=True)
    parser.add_argument(
        "--output-directory",
        type=Path,
        default=Path("ros2_ws/src/robot_experiments/config"),
    )
    args = parser.parse_args()
    prereg_path = args.prereg.resolve()
    prereg = json.loads(prereg_path.read_text(encoding="utf-8"))
    if prereg.get("attempt_id") != "attempt-21-rgbd-bev-dual-track-v1":
        raise ValueError("preregistration is not Attempt-21")
    if prereg.get("gate_collection_may_begin") is not False:
        raise ValueError("Gate collection must remain closed during scenario generation")
    config = Path(__file__).resolve().parents[1] / "ros2_ws/src/robot_experiments/config"
    bases = {
        mode: yaml.safe_load((config / f"isaac_kujiale_dataset_v2_smoke_{mode}.yaml").read_text())
        for mode in MODES
    }
    output = args.output_directory.resolve()
    output.mkdir(parents=True, exist_ok=True)
    generated = []
    for phase in PHASES:
        for mode in MODES:
            target = output / f"isaac_kujiale_dataset_v3_attempt21_{phase}_{mode}.yaml"
            payload = build_scenario(bases[mode], prereg, phase=phase, mode=mode)
            target.write_text(
                "# Generated by scripts/generate_isaac_dataset_v3_attempt21_scenarios.py.\n"
                f"# Attempt-21 prereg SHA256: {sha256_file(prereg_path)}.\n"
                + yaml.safe_dump(payload, sort_keys=False),
                encoding="utf-8",
            )
            generated.append(str(target))
    print("\n".join(generated))


if __name__ == "__main__":
    main()
